#!/usr/bin/env python3
"""
PPT Master - Host Skill Stub Sync

Regenerates the per-host discovery stubs from the canonical Claude skills tree:
.codex/skills/ for GPT (Codex CLI / ChatGPT Codex) and .gemini/skills/ for
Gemini CLI. Each stub carries the canonical SKILL.md's name/description
frontmatter verbatim (so every host triggers on the same wording as Claude
Code) plus a fixed redirect body pointing at the canonical
.claude/skills/<name>/ directory and the host's adaptation notes. The .claude
tree is the single source of truth; stubs are generated artifacts and must
never be hand-edited. preflight.py runs the --check mode as a hard gate.

The shared .agents/skills/ location is deliberately unused: Codex and Gemini
CLI both scan it, so one set there would shadow the other host's set.

Usage:
    python3 scripts/sync_codex_stubs.py [options]

Examples:
    python3 scripts/sync_codex_stubs.py                 # regenerate every host
    python3 scripts/sync_codex_stubs.py --host gemini   # regenerate one host
    python3 scripts/sync_codex_stubs.py --check         # exit 1 if any stub is stale
    python3 scripts/sync_codex_stubs.py --user          # INNerGEN/INNerCarry in Codex from any folder

Dependencies:
    None (only uses standard library)
"""
from __future__ import annotations

import argparse
import os
import re
import shutil
import sys
import tempfile
from dataclasses import dataclass, field
from pathlib import Path
from typing import Optional

_SCRIPTS_DIR = Path(__file__).resolve().parent
if str(_SCRIPTS_DIR) not in sys.path:
    sys.path.insert(0, str(_SCRIPTS_DIR))

from console_encoding import configure_utf8_stdio  # noqa: E402

# scripts/sync_codex_stubs.py: [0]=scripts [1]=ppt-master [2]=skills [3]=.claude [4]=repo
REPO_ROOT = Path(__file__).resolve().parents[4]
SRC = REPO_ROOT / ".claude" / "skills"
SYNC_CMD = "python3 .claude/skills/ppt-master/scripts/sync_codex_stubs.py"
FRONTMATTER_KEYS = ("name", "description")

_TOP_KEY_RE = re.compile(r"^([A-Za-z][\w-]*):")

GENERATED_MARKER = """# Generated @LABEL@ Skill Stubs

This directory is generated by `sync_codex_stubs.py`. Each stub carries the
canonical skill's name/description frontmatter plus a redirect body; the skill
content itself lives only under `.claude/skills/`.

Do not hand-edit files under `@DIR@`. Edit `.claude/skills`, then run:

    @SYNC_CMD@
"""

# @NAME@ / @CANONICAL@ / @LABEL@ / @DIR@ are replaced at build time. Literal
# ${SKILL_DIR} must survive into the stub, so str.format() is not used here.
STUB_BODY = """
# @NAME@ (@LABEL@ discovery stub)

This file is generated by `sync_codex_stubs.py` so @LABEL@ discovers the skill.
The authoritative skill lives in this repository at `@CANONICAL@/` — a single
source of truth shared by Claude Code, Codex and Gemini CLI. Do not hand-edit
this stub; edit the canonical tree, then re-run:

    @SYNC_CMD@

On invocation:

@STEP1@
2. Resolve paths: treat `${SKILL_DIR}` as `@CANONICAL@`. Bare relative paths
   mentioned inside the skill (`references/...`, `workflows/...`, `scripts/...`,
   `templates/...`) resolve against that directory — never against
   `@DIR@/`.
3. Run all commands from the repository root. Use the repository virtual
   environment when `.venv/` exists (`.venv\\Scripts\\python.exe` on Windows,
   `.venv/bin/python` elsewhere; create it with `setup.ps1` / `setup.sh`).
   Without it, use `python3`, or `python` on Windows installs without
   `python3.exe`.
"""

# Default step 1: load the canonical SKILL.md in full.
DEFAULT_STEP1 = """1. Read `@CANONICAL@/SKILL.md` (repo-root relative) in full and execute it
   exactly as a runtime procedure."""

# Per-skill step-1 overrides — where the canonical entry is a router, not the
# full SKILL.md (AGENTS.md / CLAUDE.md "route before full-load").
STEP1_OVERRIDES = {
    "ppt-master": """1. Read `@CANONICAL@/workflows/routing.md` (repo-root relative) first;
   load `@CANONICAL@/SKILL.md` in full only when routing selects the main SVG
   family or a workflow hands off to it.""",
}

GEMINI_HOST_NOTE = """
4. **Gemini CLI adaptation**: the canonical text was written for Claude Code.
   Where it names a Claude Code tool, use the Gemini CLI equivalent (file
   read/write/replace, `run_shell_command`, glob/search, web fetch/search,
   `activate_skill`). An AskUserQuestion or other blocking confirmation becomes
   the same question asked in chat, then end the turn and wait for the answer.
   Work described as delegated to a subagent is done by you, serially, in this
   session. Every confirmation, validation and export gate stays unchanged.
"""

CODEX_IMAGE_NOTE = """
4. **Codex adaptation**: the canonical skill was written for Claude Code, which
   shells out through `codex exec` to reach `image_gen`. Inside Codex the
   `image_gen` tool is built in — call it directly with the same
   prompt/size/quality parameters instead of spawning a nested `codex exec`,
   and keep the skill's output-path conventions.
"""

GEMINI_IMAGE_NOTE = """
5. **Images under Gemini CLI**: there is no built-in image tool. Shell out the
   way the canonical skill does (`codex exec`, needs `codex login`), or run
   `.claude/skills/ppt-master/scripts/image_gen.py` with `IMAGE_BACKEND=gemini`
   and `GEMINI_API_KEY` in `.env`. Keep the skill's output-path conventions and
   the confirmed image source; never substitute placeholder images.
"""


# User-level Codex stubs ($CODEX_HOME/skills, default ~/.codex/skills) make the
# named style skills trigger from any folder Codex is opened in. They point at
# this checkout by absolute path, so they are rewritten by `--user` (setup runs
# it) rather than shipped in the repository.
USER_SKILLS = ("innergen-style", "innercarry-style")
USER_MARKER = "generated by `sync_codex_stubs.py --user`"

USER_STUB_BODY = """
# @NAME@ (Codex user-level stub)

This file was @MARKER@ so Codex finds the
skill from any project. The skill and its tools live in the Slide Master
repository at `@REPO@`. Do not hand-edit; after moving that repository, run
`python .claude/skills/ppt-master/scripts/sync_codex_stubs.py --user` there.

On invocation:

1. Read `@REPO@/AGENTS.md`, then `@REPO@/.claude/skills/@NAME@/SKILL.md`
   in full and execute it exactly as a runtime procedure. Every
   repository-relative path in them resolves against `@REPO@`, and
   `${SKILL_DIR}` is `@REPO@/.claude/skills/@NAME@`.
2. Run repository scripts with `@REPO@` as the working directory and its
   virtual environment (`@REPO@/.venv/Scripts/python.exe` on Windows,
   `@REPO@/.venv/bin/python` elsewhere).
3. Source material comes from the folder Codex was opened in (the user's
   current project): pass its files to the scripts by absolute path. The deck
   project is created under `@REPO@/projects/` as the skill says; when the
   PPTX is exported, also copy it into the current project folder and report
   both paths.
4. Writing under `@REPO@` is outside the current workspace. If the sandbox
   blocks it, ask the user to approve the write; never move the work into the
   current project folder to avoid the prompt.
"""


@dataclass(frozen=True)
class HostTarget:
    key: str
    label: str
    dst: Path
    host_note: str = ""
    extra_notes: dict[str, str] = field(default_factory=dict)

    @property
    def rel_dir(self) -> str:
        return self.dst.relative_to(REPO_ROOT).as_posix()


HOSTS = {
    "codex": HostTarget(
        key="codex",
        label="Codex",
        dst=REPO_ROOT / ".codex" / "skills",
        extra_notes={"codex-image": CODEX_IMAGE_NOTE},
    ),
    "gemini": HostTarget(
        key="gemini",
        label="Gemini CLI",
        dst=REPO_ROOT / ".gemini" / "skills",
        host_note=GEMINI_HOST_NOTE,
        extra_notes={"codex-image": GEMINI_IMAGE_NOTE,
                     "ppt-master": GEMINI_IMAGE_NOTE},
    ),
}

# Kept for callers that predate multi-host stubs.
DST = HOSTS["codex"].dst


def _fill(text: str, host: HostTarget, name: str = "") -> str:
    return (text
            .replace("@NAME@", name)
            .replace("@CANONICAL@", f".claude/skills/{name}")
            .replace("@LABEL@", host.label)
            .replace("@DIR@", host.rel_dir)
            .replace("@SYNC_CMD@", SYNC_CMD))


def _extract_frontmatter(skill_md: Path) -> list[str]:
    """Return the raw frontmatter lines (between the two --- fences)."""
    lines = skill_md.read_text(encoding="utf-8").splitlines()
    if not lines or lines[0].strip() != "---":
        raise ValueError(f"{skill_md}: missing frontmatter opening fence")
    for i in range(1, len(lines)):
        if lines[i].strip() == "---":
            return lines[1:i]
    raise ValueError(f"{skill_md}: missing frontmatter closing fence")


def _select_keys(fm_lines: list[str], keys: tuple[str, ...]) -> list[str]:
    """Keep only the given top-level keys, preserving their raw block lines
    (folded/literal scalars keep their continuation lines verbatim)."""
    out: list[str] = []
    keep = False
    for line in fm_lines:
        m = _TOP_KEY_RE.match(line)
        if m:
            keep = m.group(1) in keys
        if keep:
            out.append(line)
    return out


def _render_stub(name: str, host: HostTarget) -> str:
    fm = _select_keys(_extract_frontmatter(SRC / name / "SKILL.md"),
                      FRONTMATTER_KEYS)
    body = STUB_BODY.replace("@STEP1@", STEP1_OVERRIDES.get(name, DEFAULT_STEP1))
    body = _fill(body + host.host_note + host.extra_notes.get(name, ""), host, name)
    return "---\n" + "\n".join(fm) + "\n---\n" + body


def _skill_names() -> list[str]:
    if not SRC.is_dir():
        raise FileNotFoundError(f"canonical skills tree not found: {SRC}")
    return sorted(p.parent.name for p in SRC.glob("*/SKILL.md"))


def build_stubs(dst: Path, host: Optional[HostTarget] = None) -> None:
    """Regenerate one host's stub tree at dst (idempotent — wipes and rewrites)."""
    host = host or HOSTS["codex"]
    if dst.exists():
        shutil.rmtree(dst)
    for name in _skill_names():
        out = dst / name / "SKILL.md"
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(_render_stub(name, host), encoding="utf-8", newline="\n")
    (dst / "_GENERATED.md").write_text(_fill(GENERATED_MARKER, host),
                                       encoding="utf-8", newline="\n")


def user_skills_dir() -> Path:
    return Path(os.environ.get("CODEX_HOME", Path.home() / ".codex")) / "skills"


def install_user_stubs(dst: Optional[Path] = None) -> list[Path]:
    """Write the USER_SKILLS stubs to the user-level Codex skills folder.
    Only files this script wrote earlier are replaced; other skills are untouched."""
    dst = dst or user_skills_dir()
    repo = REPO_ROOT.as_posix()
    written = []
    for name in USER_SKILLS:
        out = dst / name / "SKILL.md"
        if out.is_file() and USER_MARKER not in out.read_text(encoding="utf-8", errors="replace"):
            print(f"[sync_codex_stubs] skipped {out}: not written by this script", file=sys.stderr)
            continue
        fm = _select_keys(_extract_frontmatter(SRC / name / "SKILL.md"), FRONTMATTER_KEYS)
        body = (USER_STUB_BODY.replace("@NAME@", name).replace("@REPO@", repo)
                .replace("@MARKER@", USER_MARKER))
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text("---\n" + "\n".join(fm) + "\n---\n" + body, encoding="utf-8", newline="\n")
        written.append(out)
    return written


def _normalized(path: Path) -> bytes:
    """File bytes with CRLF folded to LF, so a git autocrlf checkout does not
    read as drift (content drift is what the gate exists to catch)."""
    return path.read_bytes().replace(b"\r\n", b"\n")


def _stale_for_host(host: HostTarget) -> list[str]:
    with tempfile.TemporaryDirectory() as tmp:
        fresh = Path(tmp) / "skills"
        build_stubs(fresh, host)
        fresh_files = {p.relative_to(fresh) for p in fresh.rglob("*") if p.is_file()}
        dst_files = ({p.relative_to(host.dst) for p in host.dst.rglob("*") if p.is_file()}
                     if host.dst.is_dir() else set())
        stale = []
        for rel in sorted(fresh_files | dst_files, key=str):
            a, b = host.dst / rel, fresh / rel
            if not a.is_file() or not b.is_file() or _normalized(a) != _normalized(b):
                stale.append(f"{host.rel_dir}/{rel.as_posix()}")
        return stale


def stale_stub_paths() -> list[str]:
    """Repo-relative paths that differ from a fresh build, across every host.
    Empty list means all stubs are current. Used by --check and preflight."""
    stale: list[str] = []
    for host in HOSTS.values():
        stale.extend(_stale_for_host(host))
    return stale


def check() -> int:
    stale = stale_stub_paths()
    if stale:
        print(f"[sync_codex_stubs] host stubs are STALE ({len(stale)} file(s)):",
              file=sys.stderr)
        for rel in stale:
            print(f"  - {rel}", file=sys.stderr)
        print(f"  Fix: {SYNC_CMD}", file=sys.stderr)
        return 1
    print(f"[sync_codex_stubs] stubs are current "
          f"({', '.join(h.rel_dir for h in HOSTS.values())})")
    return 0


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="Regenerate/verify the per-host (Codex, Gemini CLI) skill stubs.",
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    parser.add_argument("--check", action="store_true",
                        help="exit 1 if any host's stubs are stale; do not write")
    parser.add_argument("--host", choices=sorted(HOSTS), action="append",
                        help="limit regeneration to this host (repeatable; default: all)")
    parser.add_argument("--user", action="store_true",
                        help=f"write {', '.join(USER_SKILLS)} to the user-level Codex skills "
                             "folder so they work from any project")
    return parser


def main(argv: Optional[list[str]] = None) -> int:
    configure_utf8_stdio()
    parser = build_parser()
    args = parser.parse_args(argv)
    if args.check:
        return check()
    if args.user:
        for out in install_user_stubs():
            print(f"[sync_codex_stubs] wrote {out}")
        return 0
    for key in args.host or sorted(HOSTS):
        host = HOSTS[key]
        build_stubs(host.dst, host)
        print(f"[sync_codex_stubs] regenerated {host.rel_dir} "
              f"from {SRC.relative_to(REPO_ROOT).as_posix()} "
              f"({len(_skill_names())} skill(s), {host.label})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
